/* ── Predictor ────────────────────────────────────────────────────────── */

const predict = (code, inputs) => {
  const model = state.data.cases[code].model;
  let total = model.intercept;
  for (const [key, coefficient] of Object.entries(model.coefficients)) {
    total += coefficient * (inputs[key] ?? 0);
  }
  return total;
};

const resetInputsToLatest = (code) => {
  const spec = state.data.cases[code].inputs;
  state.inputs = {};
  for (const item of spec) state.inputs[item.key] = item.default;
};

