/* ── Theme ────────────────────────────────────────────────────────────── */

const applyTheme = (theme) => {
  document.documentElement.setAttribute('data-theme', theme);
  const toggle = document.getElementById('theme-toggle');
  if (toggle) {
    const next = theme === 'dark' ? 'light' : 'dark';
    toggle.setAttribute('aria-label', `Switch to ${next} theme`);
    toggle.setAttribute('aria-pressed', String(theme === 'dark'));
  }
  // Series colours are theme-specific, and anything that baked one into an
  // inline style is now stale, so charts and colour-carrying markup repaint.
  if (state.data) {
    renderSpreadLegend();
    renderTrendLegend();
    renderCaseCards();
    renderStatePicker();
    for (const node of document.querySelectorAll('#case-cards .reveal')) {
      node.classList.add('is-visible');
    }
  }
  redrawAllCharts();
};

const setupTheme = () => {
  const toggle = document.getElementById('theme-toggle');
  toggle?.addEventListener('click', () => {
    const next = document.documentElement.getAttribute('data-theme') === 'dark' ? 'light' : 'dark';
    try {
      localStorage.setItem('co2-theme', next);
    } catch (e) {
      /* private mode: the choice simply will not persist */
    }
    applyTheme(next);
  });

  // Follow the OS while the viewer has not chosen for themselves
  window.matchMedia('(prefers-color-scheme: dark)').addEventListener('change', (event) => {
    let stored = null;
    try {
      stored = localStorage.getItem('co2-theme');
    } catch (e) {
      /* ignore */
    }
    if (!stored) applyTheme(event.matches ? 'dark' : 'light');
  });

  // Let a host page keep an embedded copy in sync with its own theme
  window.addEventListener('message', (event) => {
    const payload = event.data;
    if (payload && payload.type === 'set-theme' && (payload.theme === 'dark' || payload.theme === 'light')) {
      applyTheme(payload.theme);
    }
  });
};

/* ── Reveal on scroll ─────────────────────────────────────────────────── */

const setupReveal = () => {
  const targets = document.querySelectorAll('.reveal');

  if (prefersReducedMotion() || !('IntersectionObserver' in window)) {
    for (const node of targets) node.classList.add('is-visible');
    return;
  }

  const observer = new IntersectionObserver(
    (entries) => {
      for (const entry of entries) {
        if (!entry.isIntersecting) continue;
        entry.target.classList.add('is-visible');
        observer.unobserve(entry.target);
      }
    },
    { threshold: 0.12, rootMargin: '0px 0px -40px 0px' }
  );

  for (const node of targets) observer.observe(node);
};

