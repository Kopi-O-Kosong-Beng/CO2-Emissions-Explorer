const init = async () => {
  setupTheme();
  showLoading();

  let payload;
  try {
    const response = await fetch('data/co2.json');
    if (!response.ok) throw new Error(`HTTP ${response.status}`);
    payload = await response.json();
  } catch (error) {
    showLoadError(String(error && error.message ? error.message : error));
    setupReveal();
    return;
  }

  state.data = payload;
  state.activeState = ORDER[0];
  resetInputsToLatest(state.activeState);

  renderFacts();
  renderSpreadLegend();
  renderTrendLegend();
  renderHoldoutLegend();
  renderCaseCards();
  renderHoldoutCards();
  renderTrendTable();
  renderStatePicker();
  renderSliders();
  updateResult();

  document.getElementById('chart-spread')?.replaceChildren();
  document.getElementById('chart-trend')?.replaceChildren();
  mountChart(document.getElementById('chart-spread'), drawSpread);
  mountChart(document.getElementById('chart-trend'), drawTrend);

  document.getElementById('reset-inputs')?.addEventListener('click', () => {
    resetInputsToLatest(state.activeState);
    renderSliders();
    updateResult();
  });

  setupReveal();
};

init();
