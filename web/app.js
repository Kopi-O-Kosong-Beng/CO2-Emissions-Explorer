const renderContributions = () => {
  const host = document.getElementById('contributions');
  if (!host) return;
  host.replaceChildren();

  const info = state.data.cases[state.activeState];
  const meta = state.data.meta.feature_meta;

  const terms = Object.entries(info.model.coefficients).map(([key, coefficient]) => ({
    key,
    short: meta[key].short,
    value: coefficient * (state.inputs[key] ?? 0),
    significant: info.model.significant.includes(key),
  }));

  const largest = Math.max(...terms.map((t) => Math.abs(t.value)), 1);

  for (const term of terms) {
    const row = el('div', { class: 'contrib-row' });

    const name = el('span', { class: 'contrib-label' }, term.short);
    if (!term.significant) {
      name.appendChild(el('span', { class: 'contrib-flag', title: 'Not significant at the 5% level' }, 'n.s.'));
    }
    row.appendChild(name);

    const track = el('div', { class: 'contrib-track' });
    const share = (Math.abs(term.value) / largest) * 50;
    const bar = el('span', {
      class: `contrib-bar ${term.value >= 0 ? 'is-up' : 'is-down'}`,
      style:
        term.value >= 0
          ? `left:50%;width:${share.toFixed(2)}%`
          : `right:50%;width:${share.toFixed(2)}%`,
    });
    track.appendChild(bar);
    row.appendChild(track);

    row.appendChild(el('span', { class: 'contrib-value' }, fmtSigned(term.value)));
    host.appendChild(row);
  }

  const note = document.getElementById('contribution-note');
  if (note) {
    note.textContent = `Baseline intercept ${fmtTonnes(info.model.intercept)} t. Terms marked n.s. are not statistically significant at the 5% level, so their contribution is not distinguishable from zero.`;
  }
};

const updateResult = () => {
  const code = state.activeState;
  const info = state.data.cases[code];
  const value = predict(code, state.inputs);

  const number = document.getElementById('result-number');
  if (number) number.textContent = fmtTonnes(value);

  const context = document.getElementById('result-context');
  if (context) {
    const latestYear = info.years[info.years.length - 1];
    const latestActual = info.co2[info.co2.length - 1];
    const delta = value - latestActual;

    context.replaceChildren();
    context.appendChild(document.createTextNode(`${info.name} recorded `));
    context.appendChild(el('strong', {}, `${fmtTonnes(latestActual)} t`));
    context.appendChild(document.createTextNode(` in ${latestYear}. This forecast sits `));
    context.appendChild(el('strong', {}, `${fmtSigned(delta)} t`));
    context.appendChild(document.createTextNode(' against it.'));
  }

  renderContributions();
};

